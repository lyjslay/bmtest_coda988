static ulong mem_test_quick(ulong start_addr, ulong end_addr, u32 *pattern, int iteration)
{
  ulong addr;
  ulong errs = 0;
  ulong incr;
  u32 val, readback;

  /* Alternate the pattern */
  incr = 1;
  if (iteration & 1) {
    incr = -incr;
    /*
     * Flip the pattern each time to make lots of zeros and
     * then, the next time, lots of ones.  We decrement
     * the "negative" patterns and increment the "positive"
     * patterns to preserve this feature.
     */
    if (*pattern & 0x80000000)
      *pattern = -(*pattern);	/* complement & increment */
    else
      *pattern = ~*(pattern);
  }
  uartlog("Pattern %08X  Writing...\n", *pattern);

  for (addr = start_addr, val = *pattern; addr < end_addr; addr+=4) {
    // if (!(addr&(0x10000-1)))
    //   uartlog("w %lX=%lX\n", addr, val);
    writel(addr, val);
    val += incr;
  }

  puts("Reading...");

  for (addr = start_addr, val = *pattern; addr < end_addr; addr+=4) {
    readback = readl(addr);
    // if (!(addr&(0x10000-1)))
    //   uartlog("r %lX=%lX\n", addr, readback);
    if (readback != val) {
      uartlog("Mem error @ 0x%08lX: found %08X, expected %08X\n",
             addr, readback, val);
      errs++;
    }
    val += incr;
  }

  return errs;
}

