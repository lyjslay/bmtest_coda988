unsigned int rand_v(unsigned int *seedp)
{
  *seedp ^= (*seedp << 13);
  *seedp ^= (*seedp >> 17);
  *seedp ^= (*seedp << 5);

  return *seedp;
}

unsigned int rand_value(void)
{
  return rand_v(&y);
}

void randseed(unsigned int seed)
{
  y = seed;
}

void fill_random_data(ulong base, ulong size)
{
  randseed(SEED);
  for (ulong m = 0; m < size; m+=4) {
    ulong value = rand_value();
    writel(base + m, value);
  }
}

void fill_data_by_pattern(ulong base, ulong size, u32 pattern)
{
  for (ulong m = 0; m < size; m+=4) {
    writel(base + m, pattern);
  }
}

int check_random_data(ulong base, ulong size)
{
  randseed(SEED);
  for (ulong m = 0; m < size; m+=4) {
    ulong value = rand_value();
    ulong readdata = readl(base + m);
    if (value != readdata)
    {
      uartlog("check_random_data failed at %lx, expect %lx, readout %lx\n", base + m, value, readdata);
      return -1;
    }
  }
  return 0;
}

