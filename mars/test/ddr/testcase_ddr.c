static void bm_bist_prbs_only_w_or_r_loop_run_init(uint32_t wr)
{
  //wr ==> 1: write, 2: read

  int ret = 0;
  uint32_t rddata;

  uint32_t sram_st;
  uint32_t sram_sp;

  uint32_t cmd[6]={0};
  int i;

  if (wr == 1) {
    uartlog("Write BIST\n");
  } else if (wr == 2) {
    uartlog("Read BIST\n");
  } else {
    uartlog("Error: wr need 1(W) or 2(R)\n");
    return;
  }
  
  // enable clock, x16_en, axi_len8
  mmio_wr32(DDR_BIST_BASE + 0x0, 0x000e000e);

  // cmd queue
  sram_st = 0;
  sram_sp = 511;
  //        op_code         start              stop        pattern    dq_inv     dm_inv    dq_rotate   repeat
  cmd[0] = (wr << 30) | (sram_st << 21) | (sram_sp << 12) | (5 << 9) | (0 << 8) | (0 << 7) | (0 << 4) | (0xf << 0);  // W  1~17  prbs  repeat0
  cmd[1] = (3 << 30) | (0xffff << 0);  // goto
  cmd[2] = 0;
  cmd[3] = 0;
  cmd[4] = 0;
  cmd[5] = 0;

  // write cmd queue
  for (i = 0; i < 6; i = i + 1) {
    mmio_wr32(DDR_BIST_BASE + 0x40 + i * 4, cmd[i]);
  };

  // specified DDR space
  mmio_wr32(DDR_BIST_BASE + 0x10, 0x00100000);
  mmio_wr32(DDR_BIST_BASE + 0x14, 0x001fffff);
  
  // specified AXI address step
  mmio_wr32(DDR_BIST_BASE + 0x18, 0x00000004);
}

static void bm_bist_prbs_wr_loop_run_init(void)
{
  //wr ==> 1: write, 2: read

  int ret = 0;
  uint32_t rddata;

  uint32_t sram_st;
  uint32_t sram_sp;

  uint32_t cmd[6]={0};
  int i;

  uartlog("Write/read BIST\n");

  // cmd queue
  sram_st = 0;
  sram_sp = 511;
  //        op_code         start              stop        pattern    dq_inv     dm_inv    dq_rotate   repeat
  cmd[0] = (1 << 30) | (sram_st << 21) | (sram_sp << 12) | (5 << 9) | (0 << 8) | (0 << 7) | (0 << 4) | (0xf << 0);  // W  1~17  prbs  repeat0
  cmd[1] = (2 << 30) | (sram_st << 21) | (sram_sp << 12) | (5 << 9) | (0 << 8) | (0 << 7) | (0 << 4) | (0xf << 0);  // R  1~17  prbs  repeat0
  cmd[2] = (3 << 30) | (0xffff << 0);  // goto
  cmd[3] = 0;
  cmd[4] = 0;
  cmd[5] = 0;

  // write cmd queue
  for (i = 0; i < 6; i = i + 1) {
    mmio_wr32(DDR_BIST_BASE + 0x40 + i * 4, cmd[i]);
  };

  // specified DDR space
  mmio_wr32(DDR_BIST_BASE + 0x10, 0x00100000);
  mmio_wr32(DDR_BIST_BASE + 0x14, 0x001fffff);
}

static void bm_bist_enable(void)
{
  // bist enable
  mmio_wr32(DDR_BIST_BASE + 0x0, 0x00010001);
  uartlog("bist start\n");
}

static void bm_bist_disable(void)
{
  // bist disable
  mmio_wr32(DDR_BIST_BASE + 0x0, 0x00010000);
  uartlog("bist stop\n");
}

