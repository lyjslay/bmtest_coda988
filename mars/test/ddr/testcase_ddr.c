static int do_perf(int argc, char **argv)
{
  int ret=0;
  uint32_t wr = strtol(argv[1], NULL, 0);
  uint32_t mem_type = strtol(argv[2], NULL, 0);

  uartlog("performance measurement\n");

  //BIST loop run
  if (wr == 9) {
    bm_bist_prbs_wr_loop_run_init();
  } else {
    // bm_bist_prbs_only_w_or_r_loop_run_init(1); //write
    // bm_bist_prbs_only_w_or_r_loop_run_init(2); //read
    bm_bist_prbs_only_w_or_r_loop_run_init(wr);
  }

  // dfi_monitor_start(0); //DDR3
  // dfi_monitor_start(1); //DDR4
  // dfi_monitor_start(2); //LPDDR4
  dfi_monitor_start(mem_type);

  dfi_monitor_rpt_trig();
  dfi_monitor_readrpt(0);  //start

  bm_bist_enable();

  //Delay 1 second
  mdelay(1000);

  dfi_monitor_rpt_trig();
  dfi_monitor_readrpt(1); //end

  dfi_monitor_rpt_print_diff();

  dfi_monitor_end();

  bm_bist_disable();

  return ret;
}

