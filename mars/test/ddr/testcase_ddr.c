uint32_t dfi_rpt_cycle_cnt[2];	//dfi_rpt_cycle_cnt[31:0]

static void dfi_monitor_start(uint32_t mem_type)
{
  // dfi_mon_mem_type[9:8] = 0 (DDR3)
  // dfi_mon_mem_type[9:8] = 1 (DDR4)
  // dfi_mon_mem_type[9:8] = 2 (LPDDR4)
  if (mem_type==0) {
    uartlog("DFI monitor init for DDR3\n");
  } else if (mem_type==1) {
    uartlog("DFI monitor init for DDR4\n");
  } else if (mem_type==2) {
    uartlog("DFI monitor init for LPDDR4\n");
  }

  mmio_write_32(DDR_TOP_BASE + 0x40, 0x001 | ((mem_type&0x3)<<8)); //dfi_mon_en[0], dfi_mon_tphy_wrdata[7:4], dfi_mon_mem_type[9:8]
}

static void dfi_monitor_end(void)
{
	mmio_write_32(DDR_TOP_BASE + 0x40, 0x0); //dfi_mon_en[0], dfi_mon_tphy_wrdata[7:4], dfi_mon_mem_type[9:8]
}

static void dfi_monitor_rpt_trig(void)
{
	mmio_write_32(DDR_TOP_BASE + 0x44, 0x1); //dfi_mon_rpt_trig[0]
}

static void dfi_monitor_readrpt(int idx)
{
	dfi_r0_mw_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x68); //dfi_r0_mw_cnt[31:0]
	dfi_r0_wr2_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x60); //dfi_r0_wr2_cnt[31:0]
	dfi_r0_wr_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x58); //dfi_r0_wr_cnt[31:0]
	dfi_r0_rd2_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x50); //dfi_r0_rd2_cnt[31:0]
	dfi_r0_rd_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x48); //dfi_r0_rd_cnt[31:0]
	dfi_r0_act_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x38); //dfi_r0_act_cnt[31:0]
	dfi_w2r_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0xB8); //dfi_w2r_cnt[31:0]
	dfi_r0_preab_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x70); //dfi_r0_preab_cnt[31:0]
	dfi_r1_preab_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x74); //dfi_r1_preab_cnt[31:0]
	dfi_r0_prepb_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x78); //dfi_r0_prepb_cnt[31:0]
	dfi_r1_prepb_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0x7C); //dfi_r1_prepb_cnt[31:0]
	dfi_rpt_cycle_cnt[idx] = mmio_read_32(DDR_TOP_BASE + 0xBC); //dfi_rpt_cycle_cnt[31:0]
}

