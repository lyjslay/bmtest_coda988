/**
 *   when to trig sclr manually.
 *   O(online) X(offline)
 *   preraw ->  postraw ->  sclr  |  tirg-sc
 *          X           X              when postraw frame-done
 *          O           X              when postraw frame-doen
 *          X           O              when preraw frame-doen to trig postraw
 *          O           O              no need, take csi vsync to start.
 */
static int isp_isr(void *priv)
{
    pattern_ctx *ctx = (pattern_ctx *)priv;
    struct isp_ctx *ictx = ctx->ptn->priv;
    uint64_t csi_bdg0, preraw0;
    static u64 now, prev, last_end;
    bool kick_pre0 = 0, kick_pre1 = 0;
    union isp_intr isp_status;
    union isp_csi_intr csi_status;
    uint64_t isp_top;

    now = timer_get_tick();

    csi_bdg0 = ctx->phys_regs[ISP_BLK_ID_CSIBDG0];
    preraw0 = ctx->phys_regs[ISP_BLK_ID_PRERAW0];
    isp_top = ctx->phys_regs[ISP_BLK_ID_ISPTOP];

    u8 frame_vld_pre0 = (ISP_RD_BITS(preraw0, REG_PRE_RAW_T, FRAME_VLD, PRE_RAW_FRAME_VLD));
    isp_status = isp_intr_status(ictx);
    csi_status = isp_csi_intr_status(ictx);
    if (csi_status.bits.FIFO_OVERFLOW_INT) {
	isp_pchk_chk_status(ctx->ptn->priv, 0xf1, 0xFFFFFFFF);

	uartlog("csi_bdg rt_pxl_cnt(%d), rt_line_cnt(%d)\n",
	    ISP_RD_REG(csi_bdg0, REG_ISP_CSI_BDG_T, CSI_RT_INFO_PXL_CNT),
	    ISP_RD_REG(csi_bdg0, REG_ISP_CSI_BDG_T, CSI_RT_INFO_LINE_CNT));
	uartlog("csi_bdg ch0 no rspd cyc(%d)\n",
	    ISP_RD_REG(csi_bdg0, REG_ISP_CSI_BDG_T, CH0_NO_RSPD_CYC_CNT));
	if (ctx->is_offline_scaler) {
	    uint32_t bus_0, bus_1, bus_2, bus_3;
	    bus_0 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA3, 0);
	    bus_1 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA3, 1);
	    bus_2 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA3, 2);
	    bus_3 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA3, 3);
	    uartlog("dma3 dbus st(%#x %#x %#x %#x)\n", bus_0, bus_1, bus_2, bus_3);

	    bus_0 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA4, 0);
	    bus_1 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA4, 1);
	    bus_2 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA4, 2);
	    bus_3 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA4, 3);
	    uartlog("dma4 dbus st(%#x %#x %#x %#x)\n", bus_0, bus_1, bus_2, bus_3);

	    bus_0 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA5, 0);
	    bus_1 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA5, 1);
	    bus_2 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA5, 2);
	    bus_3 = ispblk_dma_dbg_st(ictx, ISP_BLK_ID_DMA5, 3);
	    uartlog("dma5 dbus st(%#x %#x %#x %#x)\n", bus_0, bus_1, bus_2, bus_3);
	}
    }

    isp_intr_clr(ictx, isp_status);
    isp_csi_intr_clr(ictx, csi_status);

    if (ctx->is_stop) {
	uartlog(" intr before start?? top_st(0x%x) cbdg_st(0x%x) \n",
	    isp_status.raw, csi_status.raw);
	ISP_WR_BITS(isp_top, REG_ISP_TOP_T, REG_1, FRAME_START_PRE_EN, 0);
	ISP_WR_BITS(csi_bdg0, REG_ISP_CSI_BDG_T, CSI_INTERRUPT_CTRL, FRAME_DROP_INT_EN, 0);
	return 0;
    }

#if defined(VIP_PERFORMANCE_TEST)
    if (isp_status.bits.FRAME_START_PRE) {
        ctx->rc.sof_cnt[0]++;

	if (ctx->is_post_frame_done && !ctx->is_pre0_frame_done
	    && (ctx->rc.preraw_done_cnt[0] >= ctx->rc.postraw_proc_cnt)) {
	    ctx->is_post_frame_done = 0;

	    isp_post_trig(ictx);

	    if (mod_mask & BIT(VIP_STRESS_MOD_SC)) {
		sc_frame_done = false;
		sc_intr_mask.b.scl0_frame_end = 1;
		sc_intr_mask.b.scl1_frame_end = 1;
		sc_intr_mask.b.scl2_frame_end = 1;
		sc_intr_mask.b.scl3_frame_end = 1;
		sclr_trig_start(0);
		sclr_trig_start(1);
	    }

	    if (mod_mask & BIT(VIP_STRESS_MOD_DWA)) {
		dwa_frame_done = false;
		dwa_reset();
		dwa_init();
		dwa_engine(&dwa_cfg);
	    }

	    if (stress_cb && (cb_mask & BIT(VIP_STRESS_CB_TYPE_SOF)))
		stress_cb(VIP_STRESS_CB_TYPE_SOF);
	    else
		uartlog("### isp kick post/sc on sof\n");
	}
    }

    /* prerarw frm_done */
    if (isp_status.bits.FRAME_DONE_PRE) {
	ctx->is_pre0_frame_done = 1;
        ctx->rc.preraw_done_cnt[0]++;

	if (!ctx->is_stop)
	    kick_pre0 = 1;
	else
	    uartlog("csibdg closed, no kick frame_valid\n");
    }

    /* postraw frm_done */
    if (isp_status.bits.FRAME_DONE_POST) {
	ctx->is_post_frame_done = 1;
        ctx->rc.postraw_proc_cnt++;

	if (!ctx->is_stop)
	    kick_pre0 = 1;
	else
	    uartlog("csibdg closed, no kick frame_valid\n");
    }

    try_trig_next_frame();

    if (csi_status.bits.FIFO_OVERFLOW_INT) {
	if (stress_cb && (cb_mask & BIT(VIP_STRESS_CB_TYPE_CSIBDG_FIFO_OVERFLOW)))
	    stress_cb(VIP_STRESS_CB_TYPE_CSIBDG_FIFO_OVERFLOW);
    }

    if (csi_status.bits.FRAME_DROP_INT) {
	if (stress_cb && (cb_mask & BIT(VIP_STRESS_CB_TYPE_CSIBDG_FRAME_DROP)))
	    stress_cb(VIP_STRESS_CB_TYPE_CSIBDG_FRAME_DROP);
    }

    uartlog(" preraw_frame_vld(%d), top_st(0x%x) cbdg_st(0x%x) sof(%d) preraw(%d) postraw(%d)\n\n",
        frame_vld_pre0, isp_status.raw, csi_status.raw, ctx->rc.sof_cnt[0],
	ctx->rc.preraw_done_cnt[0], ctx->rc.postraw_proc_cnt);

    prev = now;

    return 0;
#endif

#if 0
    /* preraw shaw_up */
    if (isp_status.bits.SHAW_DONE_PRE) {
        if (!ctx->is_offline_preraw) {
            if (ISP_RD_BITS(csi_bdg, REG_ISP_CSI_BDG_T, CSI_CTRL, CSI_MODE) != 0) {
                //ISP_WR_BITS(isp_top, REG_ISP_TOP_T, REG_2, FRAME_VLD_PRE, 1);
                kick = 1;
            }
            else
                uartlog("csibdg closed, no kick frame_valid\n");
        }

        ctx->rc.sof_cnt[0]++;
    }

    /* preraw1 shaw_up */
    if (isp_status.bits.SHAW_DONE_PRE1) {
        ctx->rc.sof_cnt[1]++;
    }
#endif

    /* prerarw frm_done */
    if (isp_status.bits.FRAME_DONE_PRE) {
	ctx->is_pre0_frame_done = 1;
        ctx->rc.preraw_done_cnt[0]++;

	if (ctx->is_offline_postraw) {
	    uint64_t bufaddr = rgbmap_addr[0];

	    if (ctx->rc.preraw_done_cnt[0] & 0x01) bufaddr += 0x80000;
	    ispblk_dma_config(ictx, ISP_BLK_ID_DMA15, bufaddr);
	    if (ictx->is_hdr_on) {
		bufaddr = rgbmap_addr[1];
		if (ctx->rc.preraw_done_cnt[0] & 0x01) bufaddr += 0x80000;
		ispblk_dma_config(ictx, ISP_BLK_ID_DMA16, bufaddr);
	    }

	    uartlog("trig postraw...\n");
	    ctx->is_post_frame_done = 0;

	    if (ictx->is_tile) {
		_left_tile(ictx);
		uartlog("### left tile\n");
		isp_post_trig(ictx);
	    } else {
		if (!ctx->is_offline_scaler) {
		    uartlog("### SCALER + ");
		    sclr_trig_start(ctx->sc_inst);
		}
		isp_post_trig(ictx);
	    }
        }

        if (ctx->is_offline_preraw)
            uartlog("     frame time: %ld->%ld, %ld\n",
		    ctx->sw_trig_time/TIMER_CNT_MS, now/TIMER_CNT_MS,
		    (now - ctx->sw_trig_time)/TIMER_CNT_MS);
    }

    /* preraw1 frm_done */
    if (isp_status.bits.FRAME_DONE_PRE1) {
	ctx->is_pre1_frame_done = 1;
        ctx->rc.preraw_done_cnt[1]++;

        if (!ctx->is_offline_preraw) {
            if (!ctx->is_stop)
                kick_pre1 = 1;
            else
                uartlog("csibdg closed, no kick frame_valid\n");
        }
    }

    /* postraw frm_done */
    if (isp_status.bits.FRAME_DONE_POST) {
	ctx->is_post_frame_done = 1;
        ctx->rc.postraw_proc_cnt++;

	if (is_dci_enable && (ctx->rc.postraw_proc_cnt % DCI_LUT_UPDATE_INTERVAL == 0)) {
	    uint16_t *dci_lut = (ictx->is_tile && ictx->is_work_on_r_tile)
			      ? dci_lut1 : dci_lut0;
	    _dci_lut_update(ictx);
	    ispblk_dci_config(ictx, true, dci_lut, ARRAY_SIZE(dci_lut));
	}

	if (!ctx->is_stop) {
	    if (ctx->is_offline_postraw) {
		if (ictx->is_tile && !ictx->is_work_on_r_tile) {
		    _right_tile(ictx);
		    isp_post_trig(ictx);
		    uartlog("### right tile\n");
		} else {
		    if (ctx->is_offline_scaler) {
			uartlog("### SCALER + ");
			if (is_sclr_job_done(ctx->sc_inst))
			    sclr_trig_start(ctx->sc_inst);
		    }
		}
	    } else {
		if (ctx->is_offline_scaler) {
		    uartlog("### SCALER + ");
		    sclr_trig_start(ctx->sc_inst);
		}
	    }

	    kick_pre0 = 1;
	} else
	    uartlog("csibdg closed, no kick frame_valid\n");
    }

    /* preraw frame start */
    if (isp_status.bits.FRAME_START_PRE) {
	ctx->is_pre0_frame_done = 0;
        ctx->rc.sof_cnt[0]++;
    }

    /* preraw frame start */
    if (isp_status.bits.FRAME_START_PRE1) {
	ctx->is_pre1_frame_done = 0;
        ctx->rc.sof_cnt[1]++;
    }

#if 0
    /* preraw frm_err */
    if (isp_status.bits.FRAME_ERR_PRE) {
    }
#endif

    if (kick_pre0) {
		if ((frame_count != 11111) && --frame_count <= 0) {
		    kick_pre0 = false;
		    ISP_WR_BITS(ctx->phys_regs[ISP_BLK_ID_CSIBDG0], REG_ISP_CSI_BDG_T, CSI_CTRL, CSI_ENABLE, 0);
		    uartlog("frame_count down to zero and stop...\n ");
		} else {
		    // only get next frame if post done
		    if (ctx->is_offline_postraw && is_raw_dump)
			raw_dump_next_buf(ctx->ptn->priv);
		    if (ctx->is_offline_scaler && is_yuv_dump)
			yuv_dump_next_buf(ctx->ptn->priv);
		    isp_pre_trig(ctx->ptn->priv);
		    uartlog("### isp kick %s!!!\n", "on eof");
		}
    }

    if (kick_pre1) {
    }

    last_end = timer_get_tick();

    uartlog("%s() [2_isr_time_gap(%ld) isp_enter(%ld) isr_exit(%ld)]:",
        __func__, (now - prev)/TIMER_CNT_MS, now/TIMER_CNT_MS, last_end/TIMER_CNT_MS);
    uartlog(" preraw_frame_vld(%d), top_st(0x%x) cbdg_st(0x%x) sof(%d) preraw(%d) postraw(%d)\n\n",
        frame_vld_pre0, isp_status.raw, csi_status.raw, ctx->rc.sof_cnt[0],
	ctx->rc.preraw_done_cnt[0], ctx->rc.postraw_proc_cnt);

    prev = now;

    return 0;
}

