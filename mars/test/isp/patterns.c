static int isp_test_vip_stress(void *priv)
{
    u8 test_case, _mod_mask = 0, _cb_mask = 0;
    u32 tmp = 0;
    bool enable;

    bm_get_num("Case 2M/5M/8M: ", test_case);

    bm_get_num("Enable SC(1/0): ", enable);
    if (enable) {
	_mod_mask |= BIT(VIP_STRESS_MOD_SC);
	bm_get_num("Enable OSD(1/0): ", enable);
	if (enable) _mod_mask |= BIT(VIP_STRESS_MOD_OSD);
    }
    bm_get_num("Enable DISP(1/0): ", enable);
    if (enable) _mod_mask |= BIT(VIP_STRESS_MOD_DISP);
    bm_get_num("Enable DWA(1/0): ", enable);
    if (enable) _mod_mask |= BIT(VIP_STRESS_MOD_DWA);

    bm_get_num("Enable callback for csi fifo-overflow(1/0): ", enable);
    _cb_mask |= BIT(VIP_STRESS_CB_TYPE_SOF);
    _cb_mask |= BIT(VIP_STRESS_CB_TYPE_EOF);
    if (enable) _cb_mask |= BIT(VIP_STRESS_CB_TYPE_CSIBDG_FIFO_OVERFLOW);
    bm_get_num("Enable callback for csi frame-drop(1/0): ", enable);
    if (enable) _cb_mask |= BIT(VIP_STRESS_CB_TYPE_CSIBDG_FRAME_DROP);
    bm_get_num("Enable callback for disp catch fail(1/0): ", enable);
    if (enable) _cb_mask |= BIT(VIP_STRESS_CB_TYPE_DISP_CATCH_FAIL);

    vip_stress_config(test_case, _cb_mask, _mod_mask);
    return 0;
}
