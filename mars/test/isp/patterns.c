	    int blc_id = 0;
	    uartlog("BLC0(0), BLC1(1), BLC2(2), BLC3(3)\n");
	    bm_get_num("Which BLC to config(0~3): ", blc_id);
	    bm_get_num("enable(1)/disable(0): ", enable);
	    bm_get_num("bypass(1)/not bypass(0): ", bypass);
