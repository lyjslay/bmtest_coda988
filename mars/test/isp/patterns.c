static void raw_dump_reset(void)
{
    is_raw_dump = false;
    dump_le.addr_start = 0x120000000;
    dump_le.addr_end   = 0x190000000;
    dump_le.offset     = 0;
    dump_le.size       = 0;
    dump_se.addr_start = 0x190000000;
    dump_se.addr_end   = 0x200000000;
    dump_se.offset     = 0;
    dump_se.size       = 0;
}

/*
 * @buf: 0(le), 1(se)
 */
static void _raw_dump_next_buf(struct isp_ctx *ictx, uint8_t buf)
{
    struct dump_mem *mem = (buf == 0) ? &dump_le : &dump_se;
    uint64_t addr = mem->addr_start + mem->offset;
    if (addr > mem->addr_end) {
	uartlog("raw dump address(0x%lx) over dram size(0x%lx)\n", addr, mem->addr_end);
	return;
    }
    uartlog("update raw dump address(0x%lx)\n", addr);
    if (buf == 0) {
	ispblk_dma_setaddr(ictx, ISP_BLK_ID_DMA0, addr);
	ispblk_dma_setaddr(ictx, ISP_BLK_ID_DMA6, addr);
    } else {
	ispblk_dma_setaddr(ictx, ISP_BLK_ID_DMA1, addr);
	ispblk_dma_setaddr(ictx, ISP_BLK_ID_DMA7, addr);
    }
    mem->offset += mem->size;
}

static void raw_dump_next_buf(struct isp_ctx *ictx)
{
    _raw_dump_next_buf(ictx, 0);
    if (ictx->is_hdr_on)
	_raw_dump_next_buf(ictx, 1);
}

