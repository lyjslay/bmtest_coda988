extern int isp_intr_handler(int irqn, void *priv);

static void try_trig_next_frame(void)
{
    pattern_ctx *ctx = &m_ptn_ctx;
    bool is_ready = ctx->is_post_frame_done && ctx->is_pre0_frame_done;

    if (mod_mask & BIT(VIP_STRESS_MOD_SC))
	    is_ready &= sc_frame_done;
    if (mod_mask & BIT(VIP_STRESS_MOD_DWA))
	    is_ready &= dwa_frame_done;

    if (is_ready) {
	if ((frame_count != 11111) && --frame_count <= 0) {
	    ISP_WR_BITS(ctx->phys_regs[ISP_BLK_ID_CSIBDG0], REG_ISP_CSI_BDG_T, CSI_CTRL, CSI_ENABLE, 0);
	    uartlog("frame_count down to zero and stop...\n ");
	} else {
	    struct isp_ctx *ictx = ctx->ptn->priv;

	    ctx->is_pre0_frame_done = 0;
	    isp_pre_trig(ictx);
	    if (!stress_cb)
		uartlog("### isp set frame_vld for pre on eof!!!\n");
	}

	if (stress_cb && (cb_mask & BIT(VIP_STRESS_CB_TYPE_EOF)))
	    stress_cb(VIP_STRESS_CB_TYPE_EOF);
    }
}

static int dwa_isr(int irqn, void *priv)
{
    u8 status = dwa_intr_status();

    dwa_intr_clr(status);
    uartlog("%s: dwa-status(0x%x)\n", __func__, status);
    if (status & 0x01) {
	dwa_frame_done = true;
	try_trig_next_frame();
    }

    return 0;
}

static int sc_isr(int irqn, void *priv)
{
    union sclr_intr intr_status = sclr_intr_status();

    sclr_intr_clr(intr_status);
    sc_intr_mask.raw ^= (intr_status.raw & sc_intr_mask.raw);
    uartlog("%s: sc-status(%#x) chk-result mask(%#x)\n", __func__, intr_status.raw, sc_intr_mask.raw);
    if (sc_intr_mask.raw == 0) {
	sc_frame_done = true;
	try_trig_next_frame();

	u32 val = _reg_read(0x0a0880c0);
	if (val & 0x700) {
	    uartlog("%s: disp catch fail(%#x)\n", __func__, val);
	    _reg_write_mask(0x0a0880c0, 0x700, val);
	    if (stress_cb && (cb_mask & BIT(VIP_STRESS_CB_TYPE_DISP_CATCH_FAIL)))
		stress_cb(VIP_STRESS_CB_TYPE_DISP_CATCH_FAIL);
	}
    }

    return 0;
}

/* configure before stress-test.
 *
 * @param test_case: 2/5/8 indicate the data amount of test pattern. default 5M.
 * @param _cb_mask: refer to enum VIP_STRESS_CB_TYPE. bit0:EOF, bit1:SOF,...
 *		   Only the ones set will callback.
 * @param _mod_mask: refer to enum VIP_STRESS_MOD_TYPE. bit0:SC, bit1:DWA,...
 *
 */
void vip_stress_config(u8 test_case, u8 _cb_mask, u8 _mod_mask)
{
    struct sclr_size src, dst;
    struct isp_ctx *ictx;

    cb_mask = _cb_mask;
    mod_mask = _mod_mask;

    uartlog(" Enabled Calbacks: (SOF) (EOF) ");
    if (cb_mask & BIT(VIP_STRESS_CB_TYPE_CSIBDG_FIFO_OVERFLOW))
	uartlog("(ISP FIFO OVERFLOW) ");
    if (cb_mask & BIT(VIP_STRESS_CB_TYPE_CSIBDG_FRAME_DROP))
	uartlog("(ISP FRAME DROP) ");
    if (cb_mask & BIT(VIP_STRESS_CB_TYPE_DISP_CATCH_FAIL))
	uartlog("(DISP CATCH FAIL) ");
    uartlog("\n");

    uartlog(" Enabled Modules: (ISP) ");
    if (mod_mask & BIT(VIP_STRESS_MOD_SC)) {
	uartlog("(SC) ");
	if (mod_mask & BIT(VIP_STRESS_MOD_OSD))
	    uartlog("(OSD) ");
    }
    if (mod_mask & BIT(VIP_STRESS_MOD_DISP))
	uartlog("(DISP) ");
    if (mod_mask & BIT(VIP_STRESS_MOD_DWA))
	uartlog("(DWA) ");
    uartlog("\n");
    uartlog("--------------------------------------------------------\n");

    m_ptn_ctx.ptn = &pattern_db[7];
    m_ptn_ctx.phys_regs = isp_get_phys_reg_bases();
    request_irq(ISP_INTR_NUM, isp_intr_handler, 0, "isp_intr", &m_ptn_ctx);
    m_ptn_ctx.is_stop = 1;
    m_ptn_ctx.is_pre0_frame_done = 0;
    m_ptn_ctx.is_pre1_frame_done = 0;
    m_ptn_ctx.is_post_frame_done = 1;

    ictx = m_ptn_ctx.ptn->priv;
    switch (test_case) {
	case 2:
	    ictx->src_width = 1920;
	    ictx->src_height = 1080;
	    ictx->is_tile = 0;
	    break;
	default:
	case 5:
	    ictx->src_width = 2688;
	    ictx->src_height = 1944;
	    ictx->is_tile = 0;
	    break;
	case 8:
	    ictx->src_width = 3840;
	    ictx->src_height = 2160;
	    ictx->is_tile = 1;
	    break;
    }
    pattern_isp_flow_manual(&m_ptn_ctx);

    // set yuv/raw, sc to offline
    _reg_write(0x0A0C8010, 7);
    _reg_write(0x0A080008, 0x20);
    // set full clk speed
    _reg_write(0x0A0C8030, 0x21084210);
    _reg_write(0x0A0C8034, 0x00084210);

    // set mac to vip_sys_clk2
    _reg_write_mask(0x0A0C801C, 0x00000ff0, 0x220);
    // set vip_sys_clk2 src from mipimpll
    _reg_write_mask(0x03002020, 0x00200000, 0x00200000);
    if (m_ispctx.img_width <= 1920) {
	// mipimpll_clk/6
	_reg_write(0x03002110, 0x00060009);
    } else if (m_ispctx.img_width == 2688) {
	// default: mipimpll_clk/3
	_reg_write(0x03002110, 0x00000001);
    } else if (m_ispctx.img_width == 3840) {
	// mipimpll_clk/2
	_reg_write(0x03002110, 0x00020009);
    }

    bool osd_on = mod_mask & BIT(VIP_STRESS_MOD_OSD);
    if (mod_mask & BIT(VIP_STRESS_MOD_SC)) {
	src.w = m_ispctx.img_width;
	src.h = m_ispctx.img_height;
	dst.w = 1920;
	dst.h = 1080;
	sc_from_isp(0, false, src, dst, post_y_addr, post_u_addr, post_v_addr, osd_on);
	dst.w = m_ispctx.img_width;
	dst.h = m_ispctx.img_height;
	sc_from_isp(1, false, src, dst, post_y_addr, post_u_addr, post_v_addr, osd_on);
	dst.w = 720;
	dst.h = 480;
	sc_from_isp(2, false, src, dst, post_y_addr, post_u_addr, post_v_addr, osd_on);
	dst.w = 320;
	dst.h = 240;
	sc_from_isp(3, false, src, dst, post_y_addr, post_u_addr, post_v_addr, osd_on);
	request_irq(SCL_INTR_SCL_NUM, sc_isr, 0, "scl int", NULL);
    }

    if (mod_mask & BIT(VIP_STRESS_MOD_DISP))
	enable_disp2k_for_test();

    if (mod_mask & BIT(VIP_STRESS_MOD_DWA)) {
	u64 src_addr[3] = {BASE_OFFSET + 0x156000000, BASE_OFFSET + 0x157000000, BASE_OFFSET + 0x158000000};
	u64 dst_addr[3] = {BASE_OFFSET + 0x159000000, BASE_OFFSET + 0x15A000000, BASE_OFFSET + 0x15B000000};
	u64 addr_mesh_id = BASE_OFFSET + 0x15C000000;
	u64 addr_mesh_tbl = BASE_OFFSET + 0x15C400000;
	u16 *mesh_id = (u16*) addr_mesh_id;
	struct fb_param fb_src, fb_dst;

	fb_src.width = m_ispctx.img_width;
	fb_src.height = m_ispctx.img_height;
	fb_src.offset_x = 0;
	fb_src.offset_y = 0;
	fb_dst.width = m_ispctx.img_height;
	fb_dst.height = m_ispctx.img_width;
	fb_dst.offset_x = 0;
	fb_dst.offset_y = 0;

	uartlog("Please make sure dwa mesh_id(0x%lx) mesh_tbl(0x%lx) has been loaded into memory\n",
		addr_mesh_id, addr_mesh_tbl);
	bm_getc();
	mesh_id[2] = addr_mesh_tbl & 0x0fff;
	mesh_id[3] = (addr_mesh_tbl >> 12) & 0x0fff;
	mesh_id[4] = (addr_mesh_tbl >> 24) & 0x0fff;
	mesh_id[5] = (addr_mesh_tbl >> 36) & 0x000f;

	dwa_reset();
	dwa_init();
	dwa_intr_ctrl(0x01);
	dwa_package_cfg(0, true, &fb_src, &fb_dst, src_addr, dst_addr, addr_mesh_id, &dwa_cfg);
	request_irq(DWA_INTR_NUM, dwa_isr, 0, "dwa int", NULL);
    }
}

int vip_stress_start(void)
{
    struct isp_ctx *ictx = &m_ispctx;

    m_ptn_ctx.is_stop = 0;
    frame_count = 11111;
    m_ptn_ctx.is_pre0_frame_done = 1;
    isp_streaming(ictx, 1);
    isp_pre_trig(ictx);
    m_ptn_ctx.is_pre0_frame_done = 0;
    return 0;
}

