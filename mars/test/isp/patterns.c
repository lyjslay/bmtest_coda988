    uint64_t isptopb, csib, preraw0;
    char line[16];
    (void)line;

    frame_count = 100;

    isptopb = ctx->phys_regs[ISP_BLK_ID_ISPTOP];
    csib = ctx->phys_regs[ISP_BLK_ID_CSIBDG0];
    preraw0 = ctx->phys_regs[ISP_BLK_ID_PRERAW0];

    ISP_WR_BITS(csib, REG_ISP_CSI_BDG_T, CSI_CTRL, RESET_MODE, 1);
