void ispblk_ldci_lut_config(struct isp_ctx *ctx)
{
	u16 i = 0;
	writel(0xa06b140, 1 << 12 | 1 << 4 | 0x1);
	writel(0xa06b140, 1 << 16 | readl(0xa06b140));
	writel(0xa06b144, 1 << 4 | 0x1);
	writel(0xa06b144, 1 << 12 | readl(0xa06b144));
	for (i = 0; i < 256; i++) {
		writel(0xa06b144, (ldci_lmap[i]) << 16 | (readl(0xa06b144) & 0xffff));
		writel(0xa06b144, 1 << 8 | readl(0xa06b144));
	}
}

void ispblk_ca_lut_config(struct isp_ctx *ctx, int mode)
{
	uintptr_t cacp = ctx->phys_regs[ISP_BLK_ID_CA];
	u16 i = 0;
	union REG_ISP_CA_04 wdata;

	// 0 CA mode, 1 CP mode
	ISP_WR_BITS(cacp, REG_ISP_CA_T, REG_00, CACP_MODE, mode);

	ISP_WR_BITS(cacp, REG_ISP_CA_T, REG_00, CACP_MEM_SW_MODE, 1);

	if (mode == 0) {
		vi_pr(VI_DBG, "ca mem check\n");
		for (i = 0; i < 256; i++) {
			wdata.raw = 0;
			wdata.bits.CACP_MEM_D = reg_ca_ca_y_ratio_lut[i];
			wdata.bits.CACP_MEM_W = 1;
			ISP_WR_REG(cacp, REG_ISP_CA_T, REG_04, wdata.raw);
		}
	} else { //cp mode
		vi_pr(VI_DBG, "cp mem check\n");
		for (i = 0; i < 256; i++) {
			wdata.raw = 0;
			wdata.bits.CACP_MEM_D = ((reg_ca_cp_v_lut[i]) | (reg_ca_cp_u_lut[i] << 8) | (reg_ca_cp_y_lut[i] << 16));
			wdata.bits.CACP_MEM_W = 1;
			ISP_WR_REG(cacp, REG_ISP_CA_T, REG_04, wdata.raw);
		}
	}

	ISP_WR_BITS(cacp, REG_ISP_CA_T, REG_00, CACP_MEM_SW_MODE, 0);
}

